export function formatOrdinal(n, lang = 'en') {
  if (!n) return '';
  if (lang === 'gu') return `${n}મા`;
  const s = ['th', 'st', 'nd', 'rd'];
  const v = n % 100;
  return n + (s[(v - 20) % 10] || s[v] || s[0]);
}
